import { neon } from "@neondatabase/serverless";
import { readFile } from "node:fs/promises";

const connectionString = process.env.DATABASE_URL;

if (!connectionString) {
  throw new Error("DATABASE_URL is missing.");
}

const sql = neon(connectionString);

const fileUrl = new URL("../data/meetings.json", import.meta.url);
const meetings = JSON.parse(await readFile(fileUrl, "utf8"));

if (!Array.isArray(meetings) || meetings.length !== 6) {
  throw new Error("Expected exactly six meetings in data/meetings.json.");
}

const ids = meetings.map((meeting) => meeting.id);

if (new Set(ids).size !== meetings.length) {
  throw new Error("Duplicate meeting IDs found. Import cancelled.");
}

console.log("Creating Neon meetings table...");

await sql`
  CREATE TABLE IF NOT EXISTS meetings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_date DATE NOT NULL,
    meeting_data JSONB NOT NULL
  )
`;

console.log("Importing meetings...");

for (const meeting of meetings) {
  await sql`
    INSERT INTO meetings (id, meeting_date, meeting_data)
    VALUES (
      ${meeting.id},
      ${meeting.date}::date,
      ${JSON.stringify(meeting)}::jsonb
    )
    ON CONFLICT (id)
    DO UPDATE SET
      meeting_date = EXCLUDED.meeting_date,
      meeting_data = EXCLUDED.meeting_data
  `;

  console.log(`Imported meeting #${meeting.id}: ${meeting.date}`);
}

await sql`
  SELECT setval(
    pg_get_serial_sequence('meetings', 'id'),
    (SELECT COALESCE(MAX(id), 1) FROM meetings),
    EXISTS (SELECT 1 FROM meetings)
  )
`;

const result = await sql`
  SELECT id, meeting_date
  FROM meetings
  ORDER BY meeting_date DESC
`;

console.log("\nMigration completed successfully!");
console.log(`Meetings currently in Neon: ${result.length}`);
console.table(result);
